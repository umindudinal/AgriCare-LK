-- ============================================================================
-- AgriCare LK - Supabase (PostgreSQL) Database Setup Script
-- Tables: diseases, treatments
-- Description: Run this script in the Supabase SQL Editor to create tables
--              and populate all 22 disease classes and treatments.
-- ============================================================================

-- 1. Create Tables
CREATE TABLE IF NOT EXISTS public.diseases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    ai_model_label TEXT UNIQUE NOT NULL,
    common_name_en TEXT NOT NULL,
    common_name_si TEXT NOT NULL,
    symptoms_si TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.treatments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    disease_id BIGINT NOT NULL REFERENCES public.diseases(id) ON DELETE CASCADE,
    treatment_type TEXT NOT NULL, -- 'Organic' or 'Chemical'
    instruction_si TEXT NOT NULL
);

-- Enable Row Level Security (Optional: Allow public read access)
ALTER TABLE public.diseases ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.treatments ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read access on diseases" 
ON public.diseases FOR SELECT USING (true);

CREATE POLICY "Allow public read access on treatments" 
ON public.treatments FOR SELECT USING (true);

-- Clear existing data if re-running
TRUNCATE TABLE public.treatments, public.diseases RESTART IDENTITY CASCADE;

